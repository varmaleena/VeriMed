"""Render reviewable PostgreSQL DDL from the canonical cell metadata."""

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from app.schema import NEW_TABLES

SEPARATOR = "\n-- statement-break\n"


def statements() -> list[str]:
    dialect = postgresql.dialect()  # type: ignore[no-untyped-call]  # SQLAlchemy exposes an untyped dialect constructor.
    result = [
        "CREATE EXTENSION IF NOT EXISTS vector",
        "CREATE EXTENSION IF NOT EXISTS pgcrypto",
    ]
    tenant = "tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid"
    for table in NEW_TABLES:
        result.append(str(CreateTable(table).compile(dialect=dialect)).strip())
        name = "public." + table.name
        result.extend(
            [
                f"ALTER TABLE {name} ENABLE ROW LEVEL SECURITY",
                f"ALTER TABLE {name} FORCE ROW LEVEL SECURITY",
                f"CREATE POLICY tenant_scope ON {name} USING ({tenant}) WITH CHECK ({tenant})",
                f"REVOKE ALL ON {name} FROM PUBLIC",
                f"GRANT SELECT ON {name} TO verimed_api",
            ]
        )
        for index in sorted(table.indexes, key=lambda item: str(item.name)):
            result.append(str(CreateIndex(index).compile(dialect=dialect)))
    result += [
        "ALTER TABLE public.encounters ADD CONSTRAINT fk_encounter_assignee FOREIGN KEY (tenant_id, assigned_user_id) REFERENCES public.users (tenant_id, id)",
        """CREATE FUNCTION public.validate_claim_span() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
DECLARE canonical text;
BEGIN
 SELECT body_text INTO STRICT canonical FROM public.note_versions
 WHERE tenant_id=NEW.tenant_id AND id=NEW.note_version_id;
 IF substring(canonical FROM NEW.char_start+1 FOR NEW.char_end-NEW.char_start) IS DISTINCT FROM NEW.text THEN
  RAISE EXCEPTION 'Claim span does not match canonical note' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$""",
        "REVOKE ALL ON FUNCTION public.validate_claim_span() FROM PUBLIC",
        """CREATE TRIGGER validate_claim_span BEFORE INSERT OR UPDATE ON public.claims
FOR EACH ROW EXECUTE FUNCTION public.validate_claim_span()""",
        """CREATE FUNCTION public.reject_note_mutation() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
 RAISE EXCEPTION 'Clinical note versions are append-only' USING ERRCODE='42501';
END $$""",
        "REVOKE ALL ON FUNCTION public.reject_note_mutation() FROM PUBLIC",
        """CREATE TRIGGER reject_note_mutation BEFORE UPDATE OR DELETE OR TRUNCATE ON public.note_versions
FOR EACH STATEMENT EXECUTE FUNCTION public.reject_note_mutation()""",
        """CREATE FUNCTION public.freeze_policy_content() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
 IF ROW(NEW.version,NEW.yaml,NEW.json_schema_version) IS DISTINCT FROM ROW(OLD.version,OLD.yaml,OLD.json_schema_version) THEN
  RAISE EXCEPTION 'Policy content requires a new version' USING ERRCODE='42501';
 END IF;
 RETURN NEW;
END $$""",
        "REVOKE ALL ON FUNCTION public.freeze_policy_content() FROM PUBLIC",
        """CREATE TRIGGER freeze_policy_content BEFORE UPDATE ON public.policy_packs
FOR EACH ROW EXECUTE FUNCTION public.freeze_policy_content()""",
    ]
    return result


def render() -> str:
    return (
        "-- Generated by export_platform_schema.py; do not edit.\n"
        + SEPARATOR.join(statements())
        + "\n"
    )
